-- 听歌记录瘦身（2026-10-26）
-- 在 Supabase → SQL Editor 整份执行一次（接在 20261026000000_history_compaction.sql 后面）。
--
-- 原本每一笔播放都存一整份歌曲资料（歌名、歌手、专辑、封面，约 400 bytes），
-- 同一首歌听 50 次就存 50 份。改成：
-- - tracks：每首歌只存一份（所有人共用，歌名歌手本来就是公开资料）
-- - plays：每笔播放只记哪首歌、什么时候、听了多久（约 150 bytes）
-- - play_history 变成「视图」：读的时候自动接上歌曲资料，写的时候自动拆开存，
--   所以 App（包括还没更新的旧版）照旧读写 play_history，完全不用改
--
-- 搬资料时会核对笔数和总秒数，对不上就整份取消（旧资料完全不动）。

begin;

-- ============================================================================
-- 1. 新的两张表
-- ============================================================================

create table public.tracks (
  source     text        not null default 'netease',
  track_id   text        not null,
  track      jsonb       not null,
  updated_at timestamptz not null default now(),
  primary key (source, track_id)
);

create table public.plays (
  id               bigint      generated by default as identity primary key,
  user_id          uuid        not null default auth.uid() references auth.users on delete cascade,
  source           text        not null default 'netease',
  track_id         text        not null,
  played_at        timestamptz not null default now(),
  listened_seconds integer     not null check (listened_seconds >= 0),
  duration_seconds integer     check (duration_seconds >= 0),
  skipped          boolean     not null default false,
  context          text
);
create index plays_user_played_at on public.plays (user_id, played_at desc);

-- ============================================================================
-- 2. 搬资料（每首歌留最新的一份资料）
-- ============================================================================

insert into public.tracks (source, track_id, track, updated_at)
select distinct on (source, track_id) source, track_id, track, played_at
from public.play_history
order by source, track_id, played_at desc;

insert into public.plays
  (id, user_id, source, track_id, played_at, listened_seconds, duration_seconds, skipped, context)
select id, user_id, source, track_id, played_at, listened_seconds, duration_seconds, skipped, context
from public.play_history;

-- 之后新增的接着原本的编号
select setval(
  pg_get_serial_sequence('public.plays', 'id'),
  greatest((select coalesce(max(id), 0) from public.plays), 1)
);

-- 核对：笔数、总秒数、跳过数、歌曲数都要一样，不然整份取消
do $$
declare
  old_rows bigint; new_rows bigint;
  old_secs bigint; new_secs bigint;
  old_skips bigint; new_skips bigint;
  old_songs bigint; new_songs bigint;
begin
  select count(*), coalesce(sum(listened_seconds), 0), count(*) filter (where skipped),
         count(distinct (source, track_id))
    into old_rows, old_secs, old_skips, old_songs from public.play_history;
  select count(*), coalesce(sum(listened_seconds), 0), count(*) filter (where skipped)
    into new_rows, new_secs, new_skips from public.plays;
  select count(*) into new_songs from public.tracks;
  if old_rows <> new_rows or old_secs <> new_secs or old_skips <> new_skips or old_songs <> new_songs then
    raise exception '核对不一致，已取消：笔数 % → %，秒数 % → %，跳过 % → %，歌曲 % → %',
      old_rows, new_rows, old_secs, new_secs, old_skips, new_skips, old_songs, new_songs;
  end if;
  raise notice '核对一致：% 笔播放、% 秒、% 首歌', new_rows, new_secs, new_songs;
end;
$$;

-- ============================================================================
-- 3. 旧表换成视图（App 照旧读写 play_history）
-- ============================================================================

drop table public.play_history;

create view public.play_history with (security_invoker = true) as
  select p.id, p.user_id, p.source, p.track_id, t.track, p.played_at,
         p.listened_seconds, p.duration_seconds, p.skipped, p.context
  from public.plays p
  left join public.tracks t on t.source = p.source and t.track_id = p.track_id;

-- 写进视图：歌曲资料存（或更新）到 tracks，播放存到 plays
create function public.play_history_insert()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null or not public.is_member() then
    raise exception '只有 LyriStage 成员才能记录听歌' using errcode = '42501';
  end if;
  if new.track is not null then
    insert into public.tracks (source, track_id, track, updated_at)
    values (coalesce(new.source, 'netease'), new.track_id, new.track, now())
    on conflict (source, track_id) do update set track = excluded.track, updated_at = now();
  end if;
  insert into public.plays
    (user_id, source, track_id, played_at, listened_seconds, duration_seconds, skipped, context)
  values
    (auth.uid(), coalesce(new.source, 'netease'), new.track_id, coalesce(new.played_at, now()),
     new.listened_seconds, new.duration_seconds, coalesce(new.skipped, false), new.context)
  returning id, user_id, played_at into new.id, new.user_id, new.played_at;
  return new;
end;
$$;
create trigger play_history_insert
  instead of insert on public.play_history
  for each row execute function public.play_history_insert();

-- 从视图删（「清除听歌记录」）：用删的人自己的权限，只删得到自己的
create function public.play_history_delete()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  delete from public.plays where id = old.id;
  return old;
end;
$$;
create trigger play_history_delete
  instead of delete on public.play_history
  for each row execute function public.play_history_delete();

-- ============================================================================
-- 4. 权限
-- ============================================================================

grant select, insert, delete on public.play_history to authenticated;
grant select, delete on public.plays to authenticated;
grant select on public.tracks to authenticated;

alter table public.plays  enable row level security;
alter table public.tracks enable row level security;

-- plays：和原本的 play_history 一样，只看得到、删得了自己的，而且要是成员
create policy "read own" on public.plays
  for select to authenticated using (user_id = (select auth.uid()));
create policy "delete own" on public.plays
  for delete to authenticated using (user_id = (select auth.uid()));
create policy "members only" on public.plays
  as restrictive to authenticated
  using ((select public.is_member())) with check ((select public.is_member()));
-- tracks：歌曲资料是公开的，登录的人都能读；只能透过上面的触发器写
create policy "everyone reads tracks" on public.tracks
  for select to authenticated using (true);

-- ============================================================================
-- 5. 每月整理改成直接整理 plays（比经过视图快）
-- ============================================================================

create or replace function public.compact_play_history(keep interval default interval '13 months')
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  cutoff timestamptz := date_trunc('month', now() - keep);
  moved bigint;
begin
  with old as (
    delete from public.plays where played_at < cutoff returning *
  ),
  summary as (
    insert into public.play_history_monthly as m
      (user_id, month, source, track_id, track, plays, skips, listened_seconds)
    select o.user_id,
           date_trunc('month', o.played_at at time zone 'Asia/Kuala_Lumpur')::date,
           o.source,
           o.track_id,
           (select t.track from public.tracks t where t.source = o.source and t.track_id = o.track_id),
           count(*) filter (where not o.skipped),
           count(*) filter (where o.skipped),
           sum(o.listened_seconds)
    from old o
    group by 1, 2, 3, 4
    on conflict (user_id, month, source, track_id) do update
      set plays = m.plays + excluded.plays,
          skips = m.skips + excluded.skips,
          listened_seconds = m.listened_seconds + excluded.listened_seconds,
          track = coalesce(excluded.track, m.track)
  ),
  hours as (
    insert into public.play_hours_monthly as h (user_id, month, hour, seconds)
    select user_id,
           date_trunc('month', played_at at time zone 'Asia/Kuala_Lumpur')::date,
           extract(hour from played_at at time zone 'Asia/Kuala_Lumpur')::smallint,
           sum(listened_seconds)
    from old
    group by 1, 2, 3
    on conflict (user_id, month, hour) do update
      set seconds = h.seconds + excluded.seconds
  )
  select count(*) into moved from old;
  return moved;
end;
$$;
revoke execute on function public.compact_play_history(interval) from public, anon, authenticated;

commit;
