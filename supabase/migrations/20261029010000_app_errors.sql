-- 错误自动回报（2026-10-29）
-- 在 Supabase → SQL Editor 整份执行一次（要先执行过 20261026000000_history_compaction.sql：要用 pg_cron）。
--
-- 朋友遇到「播不了」「歌词载不出来」或 App 出错时，App 自动记一笔，管理员在设置页看得到，
-- 不用等朋友来讲。只记错误本身（哪种错、错误信息、哪首歌、哪个平台和版本），不记其他资料。
-- - 成员只能新增自己的，读不到别人的（只有管理员读得到）
-- - 每人每天最多 100 笔（App 坏掉狂报时不会把数据库塞满）
-- - 30 天以前的每天自动删掉

create table public.app_errors (
  id          bigint      generated by default as identity primary key,
  user_id     uuid        not null default auth.uid() references auth.users on delete cascade,
  created_at  timestamptz not null default now(),
  kind        text        not null check (kind in ('crash', 'playback', 'unplayable', 'lyrics')),
  message     text        not null check (char_length(message) <= 500),
  detail      text        check (char_length(detail) <= 4000),
  platform    text        not null check (platform in ('windows', 'android', 'web', 'iphone')),
  app_version text        check (char_length(app_version) <= 20),
  context     jsonb       check (pg_column_size(context) <= 2000)
);
create index app_errors_created_at on public.app_errors (created_at desc);

grant insert on public.app_errors to authenticated;
grant usage on sequence public.app_errors_id_seq to authenticated;
alter table public.app_errors enable row level security;

create policy "members report own errors" on public.app_errors
  for insert to authenticated
  with check (user_id = (select auth.uid()) and (select public.is_member()));

-- 每人每天最多 100 笔
create function public.app_errors_limit()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (select count(*) from public.app_errors
      where user_id = new.user_id and created_at > now() - interval '1 day') >= 100 then
    return null; -- 超过就安静地不记
  end if;
  return new;
end;
$$;
create trigger app_errors_limit
  before insert on public.app_errors
  for each row execute function public.app_errors_limit();

/**
 * 管理员看：最近几天的错误，同一种错误合并成一行（几次、几个人、最后一次、哪些平台和版本、谁遇到、一个例子）
 */
create function public.admin_error_summary(days integer default 7)
returns table (
  kind text, message text, times bigint, people bigint, last_at timestamptz,
  platforms text[], versions text[], names text[], example jsonb, detail text
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not public.is_admin() then
    raise exception '只有管理员能看' using errcode = '42501';
  end if;
  return query
    select e.kind,
           e.message,
           count(*),
           count(distinct e.user_id),
           max(e.created_at),
           array_agg(distinct e.platform),
           array_agg(distinct e.app_version) filter (where e.app_version is not null),
           array_agg(distinct coalesce(nullif(p.display_name, ''), '?')),
           (array_agg(e.context order by e.created_at desc))[1],
           (array_agg(e.detail order by e.created_at desc))[1]
    from public.app_errors e
    left join public.member_profiles p on p.user_id = e.user_id
    where e.created_at > now() - make_interval(days => greatest(days, 1))
    group by e.kind, e.message
    order by max(e.created_at) desc
    limit 100;
end;
$$;
revoke execute on function public.admin_error_summary(integer) from public, anon;
grant execute on function public.admin_error_summary(integer) to authenticated;

/** 管理员：全部清掉（看完、修好以后） */
create function public.admin_clear_errors()
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.is_admin() then
    raise exception '只有管理员能清除' using errcode = '42501';
  end if;
  delete from public.app_errors where true;
end;
$$;
revoke execute on function public.admin_clear_errors() from public, anon;
grant execute on function public.admin_clear_errors() to authenticated;

-- 每天 UTC 20:30（马来西亚时间凌晨 4 点半）删掉 30 天以前的
select cron.schedule(
  'clean-app-errors',
  '30 20 * * *',
  $$delete from public.app_errors where created_at < now() - interval '30 days'$$
);
